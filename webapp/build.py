#!/usr/bin/env python3
"""Builds the single-file web app (index.html) from index.src.html, generator.js,
app.js and the static deployment files, so the page works offline from file://.

Usage:
    python3 build.py           # write index.html
    python3 build.py --check   # exit 1 if index.html is out of date
"""

import json
import pathlib
import sys

WEBAPP_DIR = pathlib.Path(__file__).resolve().parent
BUNDLE_DIR = WEBAPP_DIR.parent

# Deployment files that do not depend on user input; embedded verbatim.
STATIC_FILES = [
    "conductor_template.json",
    "README.md",
]


def _replace_block(html, marker, content):
    begin = f"<!-- {marker}:BEGIN -->"
    end = f"<!-- {marker}:END -->"
    start = html.index(begin) + len(begin)
    stop = html.index(end)
    return f"{html[:start]}\n{content}\n{html[stop:]}"


def _script(code, **attrs):
    if "</script" in code.lower():
        raise ValueError("embedded code must not contain '</script'")
    attr_text = "".join(f' {k.replace("_", "-")}="{v}"' for k, v in attrs.items())
    return f"<script{attr_text}>\n{code}</script>"


def build():
    static = {
        name: (BUNDLE_DIR / name).read_text(encoding="utf-8").replace("\r\n", "\n")
        for name in STATIC_FILES
    }
    static_json = json.dumps(static, indent=1, ensure_ascii=False).replace("</", "<\\/")

    html = (WEBAPP_DIR / "index.src.html").read_text(encoding="utf-8")
    html = _replace_block(
        html, "STATIC-FILES", _script(static_json + "\n", id="static-files", type="application/json")
    )
    html = _replace_block(
        html, "GENERATOR", _script((WEBAPP_DIR / "generator.js").read_text(encoding="utf-8"), id="generator")
    )
    html = _replace_block(html, "APP", _script((WEBAPP_DIR / "app.js").read_text(encoding="utf-8"), id="app"))
    banner = "<!-- GENERATED by webapp/build.py from index.src.html - do not edit directly -->"
    doctype, rest = html.split("\n", 1)
    return f"{doctype}\n{banner}\n{rest}"


def main():
    output = WEBAPP_DIR / "index.html"
    html = build()
    if "--check" in sys.argv[1:]:
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if current != html:
            print(f"{output} is out of date; run: python3 {pathlib.Path(__file__).name}")
            return 1
        print(f"{output} is up to date")
        return 0
    output.write_text(html, encoding="utf-8")
    print(f"wrote {output} ({len(html):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
